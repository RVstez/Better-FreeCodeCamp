#!/usr/bin/env node
// Generates sw.js (the offline-cache service worker) for Better-FreeCodeCamp.
// Usage: node tools/build-sw.mjs        (also called automatically by tools/serve.mjs)
//
// It lists every file in the web root (public/, or the project root in a flat
// layout), hashes their contents into a cache version, and writes sw.js.
// sw.js is only rewritten when something changed.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

// Never cached. Only matters in a flat layout, where the web root is the project root.
const SKIP_TOP_LEVEL = new Set([
  'sw.js', 'tools', 'node_modules', 'README.md', 'TESTING.md', 'package.json', 'package-lock.json',
]);

const TEMPLATE = String.raw`// GENERATED by tools/build-sw.mjs — do not edit. Version __VERSION__.
const CACHE = 'bfcc-__VERSION__';
const FILES = __FILES__;
// Code and pages: ask the server first (so edits show up) but give up after 1.2s and use the saved copy; once it has given up, stop asking for 20s so the rest of the page doesn't each wait again, so a stalled or stopped
// server never freezes the app. Everything heavy and unchanging (Monaco, fonts, lesson data, test runner): saved copy first.
const FRESH = /(^\/$|\/index\.html$|\/js\/|\/css\/|\/data\/manifest\.json$)/;
self.addEventListener('install', (e) => { self.skipWaiting(); e.waitUntil(caches.open(CACHE).then((c) => Promise.allSettled(FILES.map((f) => c.add(f))))); });
self.addEventListener('activate', (e) => e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('bfcc-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
let downUntil = 0; // set when the server failed to answer in time
const within = (p, ms) => Promise.race([p, new Promise((_, no) => setTimeout(() => no(new Error('slow')), ms))]);
async function networkFirst(req) {
  const cache = await caches.open(CACHE);
  try {
    if (Date.now() < downUntil) throw new Error('server recently unresponsive');
    const res = await within(fetch(req, { cache: 'no-store' }), 1200); downUntil = 0; if (res.ok) cache.put(req, res.clone()); return res;
  } catch (e) { if (e.message === 'slow') downUntil = Date.now() + 20000; return (await cache.match(req, { ignoreSearch: true })) ?? (req.mode === 'navigate' ? await cache.match('index.html') : Response.error()); }
}
async function cacheFirst(req) {
  const cache = await caches.open(CACHE), hit = await cache.match(req, { ignoreSearch: true }); if (hit) return hit;
  const res = await fetch(req); if (res.ok) cache.put(req, res.clone()); return res;
}
self.addEventListener('fetch', (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== 'GET' || u.origin !== location.origin) return;
  e.respondWith(FRESH.test(u.pathname) ? networkFirst(r) : cacheFirst(r));
});
`;

function listFiles(dir, base = dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    const rel = path.relative(base, full).split(path.sep).join('/');
    if (!rel.includes('/') && SKIP_TOP_LEVEL.has(entry.name)) continue;
    if (entry.isDirectory()) listFiles(full, base, out);
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

export function buildSw(root) {
  const files = listFiles(root).sort();
  const hash = crypto.createHash('sha1');
  for (const f of files) {
    hash.update(f + '\0');
    hash.update(fs.readFileSync(path.join(root, f)));
  }
  const version = hash.digest('hex').slice(0, 10);

  const output = TEMPLATE
    .replaceAll('__VERSION__', version)
    .replace('__FILES__', () => JSON.stringify(files));

  const target = path.join(root, 'sw.js');
  let existing = null;
  try { existing = fs.readFileSync(target, 'utf8'); } catch { /* first run */ }
  const changed = existing !== output;
  if (changed) fs.writeFileSync(target, output);
  return { changed, version, count: files.length, target };
}

// CLI mode
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const publicDir = path.join(projectRoot, 'public');
  const root = fs.existsSync(path.join(publicDir, 'index.html')) ? publicDir : projectRoot;
  const { changed, version, count } = buildSw(root);
  console.log(`${changed ? 'Wrote' : 'Unchanged'} sw.js — version ${version}, ${count} files`);
}
